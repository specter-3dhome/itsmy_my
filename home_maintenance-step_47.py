# Project: HomeMaintenance
def demo():
    """Показывает основной пользовательский сценарий проекта HomeMaintenance."""
    print("=== Демо: План обслуживания дома ===\n")

    # Создаём помещения
    rooms = [
        Room("Кухня", "Грязная"),
        Room("Ванная", "Грязная"),
        Room("Спальня", "Чистая"),
        Room("Гостиная", "Грязная"),
        Room("Пора", "Грязная"),
    ]

    # Создаём работников и назначаем задачи
    workers = [
        Worker("Анна", "Мойка"),
        Worker("Борис", "Ремонт"),
        Worker("Виктория", "Уборка"),
        Worker("Григорий", "Ремонт"),
    ]

    # Создаём задачи и назначаем их
    tasks = [
        Task("Мойка пола", "Кухня", "Анна", "2026-05-25", "10:00"),
        Task("Ремонт трубы", "Ванная", "Борис", "2026-05-26", "14:00"),
        Task("Уборка пыли", "Спальня", "Виктория", "2026-05-27", "09:00"),
        Task("Ремонт стены", "Гостиная", "Григорий", "2026-05-28", "11:00"),
        Task("Мойка окон", "Пора", "Анна", "2026-05-29", "15:00"),
    ]

    # Создаём напоминания
    reminders = [
        Reminder("Не забыть проверить трубы", "2026-05-26", "08:00"),
        Reminder("Купить моющие средства", "2026-05-27", "09:00"),
        Reminder("Заказать запчасти", "2026-05-28", "10:00"),
    ]

    # Показываем состояние системы
    print("📋 Задачи:")
    for t in tasks:
        print(f"  - {t.get_task_name()} ({t.get_room_name()}) — {t.get_worker_name()} ({t.get_date()})")

    print("\n👷 Работники:")
    for w in workers:
        print(f"  - {w.get_worker_name()} — {w.get_worker_type()}")

    print("\n🏠 Помещения:")
    for r in rooms:
        print(f"  - {r.get_room_name()} — {r.get_room_status()}")

    print("\n⏰ Напоминания:")
    for rem in reminders:
        print(f"  - {rem.get_reminder_text()} ({rem.get_reminder_date()})")

    print("\n✅ Демо завершено. Проект HomeMaintenance работает корректно!")
